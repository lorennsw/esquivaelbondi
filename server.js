const http=require('http'),fs=require('fs'),path=require('path'),{WebSocketServer}=require('ws');
const html=fs.readFileSync(path.join(__dirname,'public/index.html'));
const srv=http.createServer((q,r)=>{r.writeHead(200,{'Content-Type':'text/html; charset=utf-8'});r.end(html)});
const wss=new WebSocketServer({server:srv});
const players=new Map();let best={},id=0,oid=0,t=0;
const send=m=>{const s=JSON.stringify(m);wss.clients.forEach(c=>c.readyState==1&&c.send(s))};
wss.on('connection',ws=>{const me={id:++id,name:'?',x:.5,vivo:true,pts:0};
 ws.on('message',d=>{try{const m=JSON.parse(d);
  if(m.name)me.name=String(m.name).slice(0,15);
  if(m.x!=null)me.x=+m.x||0;
  if(m.pts!=null)me.pts=+m.pts|0;
  if(m.vivo!=null)me.vivo=!!m.vivo;
  if(me.pts>(best[me.name]||0))best[me.name]=me.pts;
  players.set(me.id,me)}catch{}});
 ws.on('close',()=>players.delete(me.id));ws.send(JSON.stringify({yo:me.id}))});
setInterval(()=>{t++;const n=[],d=Math.min(.35,.06+t/6000);
 if(Math.random()<d)n.push({id:++oid,x:Math.random(),v:.4+Math.random()*.4+Math.min(1,t/5000),e:Math.random()*6|0});
 const top=Object.entries(best).sort((a,b)=>b[1]-a[1]).slice(0,10);
 send({n,p:[...players.values()],top})},50);
srv.listen(process.env.PORT||3000);
